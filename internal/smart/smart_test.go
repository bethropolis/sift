func TestReasonMessages(t *testing.T) {
	e := New(100)
	if skip, reason := e.ShouldSkip("main.go", nil, 200); !skip || reason == "" {
		t.Errorf("guardrail = (%v, %q), want (true, non-empty)", skip, reason)
	}

	if skip, reason := e.ShouldSkip("generated.pb.go", []byte("// DO NOT EDIT\n"), 10); !skip || reason != "Auto-generated file header detected" {
		t.Errorf("header = (%v, %q)", skip, reason)
	}

	if skip, reason := e.ShouldSkip("go.sum", nil, 10); !skip || reason != "Matched smart language filter" {
		t.Errorf("language rule = (%v, %q)", skip, reason)
	}
}
