type initOptions struct {
	force  bool
	dryRun bool
	stdout bool
}

func newInitCmd(cfg *config.Config) *cobra.Command {
	opts := &initOptions{}
	cmd := &cobra.Command{
		Use:   "init [path]",
		Short: "Generate a .sift.toml for this project",
		Long: `Inspect a project and write a starting .sift.toml with sensible
ignore rules and a signatures split for heavy peripheral directories.

The generated file is validated before it is written.`,
		Args: cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) > 0 {
				cfg.RootDir = args[0]
			}
			if err := applyProfile(cfg, cmd); err != nil {
				return err
			}
			abs, err := filepath.Abs(cfg.RootDir)
			if err != nil {
				return err
			}
			target := filepath.Join(abs, ".sift.toml")
			if _, err := os.Stat(target); err == nil && !opts.force {
				return fmt.Errorf("%s already exists; pass --force to overwrite", target)
			}

			application, err := app.NewBuffered(cfg)
			if err != nil {
				return err
			}
			defer application.Close()
			ctx := cmd.Context()
			metas, skipped, err := application.SkeletonPicker(ctx)
			if err != nil {
				return err
			}
			generated := generateSiftConfig(abs, metas, cfg)
			if err := validateGenerated(abs, generated); err != nil {
				return fmt.Errorf("generated config failed validation: %w", err)
			}
			if opts.dryRun || opts.stdout {
				fmt.Fprint(cmd.OutOrStdout(), generated)
			} else {
				if err := os.WriteFile(target, []byte(generated), 0o644); err != nil {
					return err
				}
				if !cfg.Quiet {
					errOut := cmd.ErrOrStderr()
					fmt.Fprintf(errOut, "Wrote %s (%d files scanned, %d skipped)\n", target, len(metas), len(skipped))
					fmt.Fprintln(errOut, "Next: sift stats , then sift dump --budget 60000")
				}
			}
			return nil
		},
	}
	cmd.Flags().BoolVar(&opts.force, "force", opts.force, "Overwrite an existing .sift.toml")
	cmd.Flags().BoolVar(&opts.dryRun, "dry-run", opts.dryRun, "Print the generated config instead of writing it")
	cmd.Flags().BoolVar(&opts.stdout, "stdout", opts.stdout, "Print the generated config instead of writing it")
	config.RegisterFlags(cfg, cmd.Flags())
	return cmd
}

// generateSiftConfig derives a minimal valid config from the file skeleton.
// Sizes are converted to a rough token estimate (bytes/4); no file contents
// are read, so init stays fast on large repositories.
func generateSiftConfig(root string, metas []walker.FileMeta, cfg *config.Config) string {
	dirTokens := map[string]int{}
	total := 0
	languages := map[string]int{}
	manifests := map[string]bool{}
	for _, m := range metas {
		tokens := int(m.Size) / 4
		if tokens < 1 {
			tokens = 1
		}
		total += tokens
		dir := strings.SplitN(filepath.ToSlash(m.Path), "/", 2)[0]
		if !strings.Contains(filepath.ToSlash(m.Path), "/") {
			dir = ""
		}
		dirTokens[dir] += tokens
		ext := strings.TrimPrefix(strings.ToLower(filepath.Ext(m.Path)), ".")
		if ext != "" {
			languages[ext]++
		}
		switch filepath.Base(m.Path) {
		case "go.mod", "package.json", "Cargo.toml", "pyproject.toml", "Gemfile", "pom.xml", "build.gradle":
			manifests[filepath.Base(m.Path)] = true
		}
	}

	var heavy []string
	for dir, tokens := range dirTokens {
		if dir == "" || isCoreDir(dir) || total == 0 {
			continue
		}
		if float64(tokens)/float64(total) >= 0.15 {
			heavy = append(heavy, dir)
		}
	}
	sort.Strings(heavy)

	var b strings.Builder
	b.WriteString("# Generated by sift init. Review and commit this file.\n\n")
	b.WriteString("[sift]\n")
	style := cfg.Style
	if style == "" {
		style = "markdown"
	}
	fmt.Fprintf(&b, "style = %s\n", strconv.Quote(style))
	if cfg.Budget > 0 {
		fmt.Fprintf(&b, "budget = %d\n", cfg.Budget)
	}
	b.WriteString("ignore = [\"codebase.md\", \"guidance.md\", \".sift.toml\"]\n")
	if len(heavy) > 0 {
		b.WriteString("\n[modes]\nsignatures = [\n")
		for _, dir := range heavy {
			fmt.Fprintf(&b, "  %s,\n", strconv.Quote(dir+"/**"))
		}
		b.WriteString("]\n")
	}
	for _, name := range []string{"AGENTS.md", "README.md"} {
		path := filepath.Join(root, name)
		if info, err := os.Stat(path); err == nil && info.Mode().IsRegular() {
			fmt.Fprintf(&b, "\n[[targets]]\nname = \"guidance\"\noutput = \"guidance.md\"\nstyle = \"markdown\"\nprompt_file = %s\n", strconv.Quote(name))
			break
		}
	}
	return b.String()
}

func isCoreDir(dir string) bool {
	switch dir {
	case "src", "internal", "cmd", "app", "lib", "pkg", "main", "test", "tests":
		return true
	}
	return false
}

func validateGenerated(root, body string) error {
	f, err := os.CreateTemp("", "sift-init-*.toml")
	if err != nil {
		return err
	}
	path := f.Name()
	defer os.Remove(path)
	if _, err := f.WriteString(body); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	result, err := config.ValidateConfigFile(path, root)
	if err != nil {
		return err
	}
	for _, issue := range result.Issues {
		if issue.Severity == config.SeverityError {
			return fmt.Errorf("%s: %s", issue.Field, issue.Message)
		}
	}
	return nil
}
