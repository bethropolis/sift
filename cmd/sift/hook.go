package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"

	"github.com/bethropolis/sift/internal/config"
)

const hookMarker = "generated by sift hook install"

// gitHooksDir resolves the real hooks directory, honoring worktrees and
// core.hooksPath via git itself.
func gitHooksDir(root string) (string, error) {
	cmd := exec.Command("git", "-C", root, "rev-parse", "--git-path", "hooks")
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("not a git repository: %w", err)
	}
	dir := strings.TrimSpace(string(out))
	if dir == "" {
		return "", fmt.Errorf("git returned an empty hooks path")
	}
	if !filepath.IsAbs(dir) {
		dir = filepath.Join(root, dir)
	}
	return filepath.Clean(dir), nil
}

// hookScript builds a self-contained hook that runs the configured targets.
func hookScript(hook string, targets []string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	fmt.Fprintf(&b, "# %s — remove with `sift hook uninstall`\n", hookMarker)
	b.WriteString("set -e\n")
	if len(targets) == 0 {
		b.WriteString("sift dump --quiet\n")
	} else {
		for _, target := range targets {
			fmt.Fprintf(&b, "sift dump --quiet --target %q\n", target)
		}
	}
	return b.String()
}

func newHookCmd(cfg *config.Config) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "hook",
		Short: "Install Git hooks that regenerate configured targets",
	}
	cmd.AddCommand(newHookStatusCmd(cfg), newHookInstallCmd(cfg), newHookUninstallCmd(cfg))
	return cmd
}

func resolveHookConfig(cfg *config.Config, cmd *cobra.Command, args []string) (string, string, []string, error) {
	if len(args) > 0 {
		cfg.RootDir = args[0]
	}
	if err := applyProfile(cfg, cmd); err != nil {
		return "", "", nil, err
	}
	root, err := filepath.Abs(cfg.RootDir)
	if err != nil {
		return "", "", nil, err
	}
	hook := cfg.Automation.GitHook
	if hook == "" {
		return root, "", nil, fmt.Errorf("[automation].git_hook is not set in .sift.toml")
	}
	if strings.ContainsAny(hook, `/\`) || hook == "." || hook == ".." {
		return root, "", nil, fmt.Errorf("invalid hook name %q", hook)
	}
	return root, hook, cfg.Automation.HookTargets, nil
}

func newHookStatusCmd(cfg *config.Config) *cobra.Command {
	return &cobra.Command{
		Use:   "status [path]",
		Short: "Show whether the configured hook is installed",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			root, hook, targets, err := resolveHookConfig(cfg, cmd, args)
			if err != nil {
				return err
			}
			dir, err := gitHooksDir(root)
			if err != nil {
				return err
			}
			path := filepath.Join(dir, hook)
			data, readErr := os.ReadFile(path)
			switch {
			case readErr == nil && strings.Contains(string(data), hookMarker):
				fmt.Fprintf(cmd.OutOrStdout(), "%s: installed (%s)\n", hook, path)
			case readErr == nil:
				fmt.Fprintf(cmd.OutOrStdout(), "%s: foreign hook at %s\n", hook, path)
			case os.IsNotExist(readErr):
				fmt.Fprintf(cmd.OutOrStdout(), "%s: not installed (%s)\n", hook, path)
			default:
				return readErr
			}
			if len(targets) > 0 {
				fmt.Fprintf(cmd.OutOrStdout(), "targets: %s\n", strings.Join(targets, ", "))
			}
			return nil
		},
	}
}

func newHookInstallCmd(cfg *config.Config) *cobra.Command {
	var force bool
	cmd := &cobra.Command{
		Use:   "install [path]",
		Short: "Install the configured Git hook",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			root, hook, targets, err := resolveHookConfig(cfg, cmd, args)
			if err != nil {
				return err
			}
			dir, err := gitHooksDir(root)
			if err != nil {
				return err
			}
			if err := os.MkdirAll(dir, 0o755); err != nil {
				return err
			}
			path := filepath.Join(dir, hook)
			if data, err := os.ReadFile(path); err == nil && !strings.Contains(string(data), hookMarker) && !force {
				return fmt.Errorf("%s is not managed by sift; pass --force to replace it", path)
			}
			if err := os.WriteFile(path, []byte(hookScript(hook, targets)), 0o755); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "Installed %s\n", path)
			return nil
		},
	}
	cmd.Flags().BoolVar(&force, "force", force, "Replace an existing hook not created by sift")
	return cmd
}

func newHookUninstallCmd(cfg *config.Config) *cobra.Command {
	return &cobra.Command{
		Use:   "uninstall [path]",
		Short: "Remove a Sift-managed Git hook",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			root, hook, _, err := resolveHookConfig(cfg, cmd, args)
			if err != nil {
				return err
			}
			dir, err := gitHooksDir(root)
			if err != nil {
				return err
			}
			path := filepath.Join(dir, hook)
			data, err := os.ReadFile(path)
			if os.IsNotExist(err) {
				fmt.Fprintf(cmd.OutOrStdout(), "%s is not installed\n", hook)
				return nil
			}
			if err != nil {
				return err
			}
			if !strings.Contains(string(data), hookMarker) {
				return fmt.Errorf("%s is not managed by sift; leaving it alone", path)
			}
			if err := os.Remove(path); err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "Removed %s\n", path)
			return nil
		},
	}
}
